// one cache key per page: /x, /x.html and /x?anything are the same page
function pageKey(url) {
  let p = url.pathname.replace(/\.html$/, '').replace(/\/index$/, '/');
  if (p.length > 1) p = p.replace(/\/$/, '');
  return url.origin + p;
}
